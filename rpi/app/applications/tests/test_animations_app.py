def unhex(text):
    return [int(text[i:i + 4], 16) for i in range(0, len(text), 4)]


class FakeDisplay:
    def __init__(self):
        self.cells = []

    def show_cells(self, cells):
        self.cells.append(list(cells))


class TimedButtons:
    """Die Uhr laeuft nur beim Warten; Tasten kommen zu festen Zeiten, BT4 am Ende."""

    def __init__(self, now, presses=(), end=60.0):
        self.now, self.presses, self.end = now, sorted(presses), end

    def get(self, timeout):
        before = self.now[0]
        self.now[0] += timeout
        for entry in self.presses:
            if before < entry[0] <= self.now[0]:
                self.presses.remove(entry)
                return entry[1]
        return BT4 if self.now[0] >= self.end else None

    def drain(self):
        pass


class Recorder(AnimationsApp):
    """Merkt sich, welche Animation zu welcher Zeit gebaut wurde."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.built = []

    def _build(self, name, t):
        self.built.append((name, t))
        return super()._build(name, t)


START = 100.0


def run_app(presses=(), end=60.0, seed=1):
    now = [START]
    display = FakeDisplay()
    times = []
    original = display.show_cells

    def show(cells):
        times.append(now[0] - START)
        original(cells)

    display.show_cells = show
    buttons = TimedButtons(now, [(START + t, b) for t, b in presses], START + end)
    app = Recorder(clock=lambda: now[0], rng=random.Random(seed))
    ctx = AppContext(display, buttons, Activity(), StopSignal())
    with_stop = None
    try:
        app.run(ctx)
    except StopApp as stop:
        with_stop = stop
    assert with_stop is not None
    return app, display, times


class ZeroRng:
    def random(self):
        return 0.0


class ReferenceTest(unittest.TestCase):
    def test_deterministic_animations_match_the_template(self):
        app = AnimationsApp(rng=random.Random(1))
        for name, cases in REF_T.items():
            for t, expected in cases:
                with self.subTest(name=name, t=t):
                    self.assertEqual(app._build(name, t), unhex(expected))

    def test_pacman_matches_the_template_step_by_step(self):
        app = AnimationsApp(rng=random.Random(1))
        app._reset()
        wanted = {k: (ph, h) for k, ph, h in REF_PAC}
        for k in range(0, 91):
            if k:
                app._advance("pacman")
            if k in wanted:
                phase, expected = wanted[k]
                with self.subTest(step=k):
                    self.assertEqual(app._anim.pac["phase"], phase)
                    self.assertEqual(app._build("pacman", 0.0), unhex(expected))
        self.assertEqual({ph for _, ph, _ in REF_PAC}, {"rechts", "links", "punkte"})


class RandomAnimationsTest(unittest.TestCase):
    def make(self, seed=3):
        app = AnimationsApp(rng=random.Random(seed))
        app._reset()
        return app

    def check_frame(self, buf):
        self.assertEqual(len(buf), 96)
        self.assertTrue(all(0 <= v <= 0xFFFF for v in buf))

    def test_rain_drops_stay_in_the_wall(self):
        app = self.make()
        self.assertEqual(len(app._anim.drops), 22)
        for _ in range(400):
            app._advance("regen")
            for d in app._anim.drops:
                self.assertTrue(0 <= d["lane"] < 72)
                self.assertTrue(-6 <= d["p"] <= 8)
                self.assertTrue(0 <= d["splash"] <= 2)
            self.check_frame(app._build("regen", 0.0))

    def test_fireworks_rockets_stay_in_the_wall_and_vanish(self):
        app = self.make()
        seen = 0
        for _ in range(400):
            app._advance("feuerwerk")
            for r in app._anim.rockets:
                seen += 1
                self.assertTrue(2 <= r["c"] <= 21)
                self.assertTrue(2 <= r["top"] <= 5)
                self.assertTrue(r["top"] - 1 <= r["p"] <= 8)
                self.assertTrue(0 <= r["k"] < 7)
            self.assertLessEqual(len(app._anim.rockets), 6)
            self.check_frame(app._build("feuerwerk", 0.0))
        self.assertGreater(seen, 20)

    def test_pong_ball_stays_in_the_court_and_the_game_goes_on(self):
        app = self.make()
        resets = 0
        for _ in range(3000):
            bx = app._anim.pong["bx"]
            app._advance("pong")
            p = app._anim.pong
            self.assertTrue(0 <= p["by"] <= 7)
            self.assertTrue(-1 <= p["bx"] <= 24)
            self.assertTrue(1 <= p["lp"] <= 6 and 1 <= p["rp"] <= 6)
            if p["bx"] == 12 and bx != 12:
                resets += 1
            self.check_frame(app._build("pong", 0.0))
        self.assertGreater(resets, 0)

    def test_pong_ball_bounces_back_from_a_paddle(self):
        app = self.make()
        app._anim.pong.update(bx=2, by=3, dx=-1, dy=1, lp=3, rp=4, wait=0)
        app._advance("pong")
        self.assertEqual(app._anim.pong["bx"], 1)
        self.assertEqual(app._anim.pong["dx"], 1)
        app._anim.pong.update(bx=21, by=3, dx=1, dy=1, lp=3, rp=3, wait=0)
        app._advance("pong")
        self.assertEqual(app._anim.pong["bx"], 22)
        self.assertEqual(app._anim.pong["dx"], -1)

    def test_pong_ball_bounces_off_top_and_bottom(self):
        app = self.make()
        app._anim.pong.update(bx=12, by=6, dx=1, dy=1, wait=0)
        app._advance("pong")
        self.assertEqual((app._anim.pong["by"], app._anim.pong["dy"]), (7, -1))
        app._advance("pong")
        self.assertEqual(app._anim.pong["by"], 6)
        app._anim.pong.update(bx=12, by=1, dx=1, dy=-1, wait=0)
        app._advance("pong")
        self.assertEqual((app._anim.pong["by"], app._anim.pong["dy"]), (0, 1))

    def test_pong_missed_ball_starts_a_new_round(self):
        app = self.make()
        app._anim.pong.update(bx=0, by=7, dx=-1, dy=1, lp=1, rp=4, wait=0)
        app._advance("pong")
        p = app._anim.pong
        self.assertEqual((p["bx"], p["dx"], p["wait"]), (12, 1, 4))

    def test_pong_waits_before_the_first_move(self):
        app = self.make()
        before = dict(app._anim.pong)
        for _ in range(4):
            app._advance("pong")
        self.assertEqual(app._anim.pong["bx"], before["bx"])
        self.assertEqual(app._anim.pong["wait"], 0)

    def test_matrix_shows_only_characters_from_mch(self):
        app = self.make()
        allowed = {0} | {ASCII_16SEG[ch] for ch in MCH}
        shown = set()
        for _ in range(300):
            app._advance("matrix")
            buf = app._build("matrix", 0.0)
            self.check_frame(buf)
            self.assertTrue(set(buf) <= allowed)
            shown |= set(buf)
        self.assertGreater(len(shown), 10)
        for s in app._anim.matrix:
            self.assertTrue(all(ch in MCH for ch in s["ch"]))

    def test_matrix_stream_restarts_when_below_the_wall(self):
        app = self.make()
        app._anim.matrix[0].update(h=10.0, v=0.3, len=2)
        app._advance("matrix")
        self.assertLess(app._anim.matrix[0]["h"], 0.0)

    def test_reset_makes_a_fresh_state_each_time(self):
        app = AnimationsApp(rng=ZeroRng())
        app._reset()
        app._advance("regen")
        app._advance("feuerwerk")
        self.assertEqual(len(app._anim.rockets), 1)
        app._reset()
        self.assertEqual(app._anim.rockets, [])
        self.assertEqual(app._anim.pac["x"], -1)
        self.assertEqual(app._anim.step, 0)


class UpdateTest(unittest.TestCase):
    def make(self, manual=0):
        app = AnimationsApp(rng=random.Random(5))
        app._reset()
        app._manual = manual
        return app

    def test_order_and_step_times_come_from_the_template(self):
        self.assertEqual(ANIMS, ["equalizer", "regen", "welle", "tunnel", "feuerwerk", "pacman",
                                 "laufschrift", "schlange", "pong", "matrix", "lauflicht"])
        self.assertEqual(ANIM_IV["pacman"], 0.16)
        self.assertEqual(ANIM_IV["lauflicht"], 0.05)
        self.assertEqual(len(ANIM_IV), 11)

    def test_animation_changes_every_ten_seconds(self):
        app = self.make()
        names = [app._current(t) for t in (0, 9.99, 10, 19.9, 20, 109.9, 110, 120)]
        self.assertEqual(names, ["equalizer", "equalizer", "regen", "regen", "welle",
                                 "lauflicht", "equalizer", "regen"])

    def test_manual_offset_shifts_the_animation(self):
        self.assertEqual(self.make(manual=3)._current(5.0), "tunnel")
        self.assertEqual(self.make(manual=11)._current(5.0), "equalizer")

    def test_same_animation_and_step_gives_no_new_picture(self):
        app = self.make()
        self.assertIsNotNone(app._update(0.01))
        self.assertIsNone(app._update(0.02))
        self.assertIsNone(app._update(0.099))
        self.assertIsNotNone(app._update(0.101))

    def test_new_animation_gives_a_picture_with_one_step(self):
        app = self.make(manual=1)  # bei t = 0 laeuft der Regen
        self.assertIsNotNone(app._update(0.0))
        self.assertEqual(app._anim.step, 1)
        self.assertIsNotNone(app._update(10.5))  # Welle: neue Animation, ein Schritt
        self.assertEqual(app._anim.step, 2)

    def test_steps_are_limited_to_five(self):
        app = self.make(manual=1)  # Regen, 0.08 s je Schritt
        app._update(0.0)
        app._update(0.08 * 3.5)
        self.assertEqual(app._anim.step, 1 + 3)
        app._update(0.08 * 40.5)
        self.assertEqual(app._anim.step, 1 + 3 + 5)

    def test_animations_without_a_step_function_do_not_touch_state(self):
        app = self.make()
        before = [dict(d) for d in app._anim.drops]
        app._update(0.0)
        app._update(0.55)
        self.assertEqual([dict(d) for d in app._anim.drops], before)
        self.assertEqual(app._anim.step, 1 + 5)  # der Zaehler laeuft trotzdem mit


class RunTest(unittest.TestCase):
    def test_name(self):
        self.assertEqual(AnimationsApp().name, "ANIMATIONEN")

    def test_rotates_every_ten_seconds(self):
        app, display, times = run_app(end=35.0)
        first = {}
        for name, t in app.built:
            first.setdefault(name, t)
        self.assertEqual(list(first), ["equalizer", "regen", "welle", "tunnel"])
        self.assertLess(first["equalizer"], 0.01)
        for name, start in (("regen", 10.0), ("welle", 20.0), ("tunnel", 30.0)):
            self.assertAlmostEqual(first[name], start, delta=0.06)
        for name, t in app.built:
            self.assertEqual(name, ANIMS[int(t // 10)])

    def test_pictures_only_when_something_changed_and_at_most_20_per_second(self):
        app, display, times = run_app(end=12.0)
        self.assertEqual(len(display.cells), len(app.built))
        for before, after in zip(times, times[1:]):
            self.assertGreaterEqual(after - before, 0.0499)
        self.assertGreater(len(display.cells), 50)
        for cells in display.cells:
            self.assertEqual(len(cells), 96)

    def test_bt6_jumps_to_the_next_animation_at_once(self):
        app, display, times = run_app(presses=[(3.0, BT6)], end=8.0)
        before = {n for n, t in app.built if t < 3.0}
        after = [(n, t) for n, t in app.built if t >= 3.0]
        self.assertEqual(before, {"equalizer"})
        self.assertEqual(after[0][0], "regen")
        self.assertLess(after[0][1], 3.2)
        self.assertEqual({n for n, _ in after}, {"regen"})

    def test_bt6_shifts_the_following_rotation_too(self):
        app, _, _ = run_app(presses=[(3.0, BT6), (4.0, BT6)], end=12.0)
